#!/usr/bin/env bash
# Weekly (Saturday) refresh of the portable Quit 9to5 content-workflow repo from the live box.
#
# GENERATED (rewritten by this script on every run):
#   playbooks/                              living rulebooks, sanitised copies
#   examples/<reel>/                        text-only script/caption/Threads files of approved reels
#   examples/README.md                      index of the above
#   skills/instagram-reel-script/SKILL.md   skill snapshot + 21 Nov playbook patch
#
# CURATED (never written by this script; a human/agent edits them after reviewing the diff):
#   README.md SETUP.md SYNC.md CHANGELOG.md NOTICE .env.example .gitignore
#   docs/ rules/ prompts/ scripts/ skills/instagram-reel-script/PLAYBOOK_PATCH.md
#   For scripts/, this job only reports upstream drift (scripts/UPSTREAM.tsv) so the port can be redone by hand.
#
# Safe to rerun: output depends only on the box sources, so a second run with no source change reports "no changes".
# Never copies manuscript.md, the part-one draft, media, .env, secrets, Quora or Reddit material.
# Ends with a secret scan of the whole repo and exits non-zero if anything real-looking is found.
#
# Usage: scripts/sync_from_box.sh [--dry-run] [--update-upstream]
set -euo pipefail

DRY_RUN=0
UPDATE_UPSTREAM=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    --update-upstream) UPDATE_UPSTREAM=1 ;;
    -h|--help) sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEST="${DEST:-$(cd "$SCRIPT_DIR/.." && pwd)}"
export Q9_ROOT="${Q9_ROOT:-/workspace/quit9to5}"
export Q9_MOTION_DIR="${Q9_MOTION_DIR:-$Q9_ROOT/motion}"
export Q9_REELS_DIR="${Q9_REELS_DIR:-$Q9_MOTION_DIR/reels}"
export Q9_SKILLS_DIR="${Q9_SKILLS_DIR:-/home/box/agent-data/workflows}"
# Space-separated script folders of approved reels to mirror into examples/. The L2 build folder is <name>_L2.
APPROVED_REELS="${APPROVED_REELS:-004_runway 005_toxic_hike}"
PY="${PYTHON:-python3}"
SAN="$SCRIPT_DIR/lib/sanitise.py"
DROP="quora,reddit"

# Text-only allow-list for examples, and hard exclusions everywhere.
EXAMPLE_EXT_RE='\.(md|txt)$'
NEVER_RE='(manuscript\.md|part-one-draft|source-accounts\.md|\.env$|\.(mp4|wav|mp3|mov|png|jpg|jpeg|webp|gif|pdf|docx)$)'

die() { echo "sync_from_box: ERROR: $*" >&2; exit 1; }
need() { [ -e "$1" ] || die "missing source: $1 (set Q9_ROOT / Q9_REELS_DIR / Q9_SKILLS_DIR)"; }

[ -f "$DEST/README.md" ] || die "DEST=$DEST does not look like the repo root (no README.md)"
command -v "$PY" >/dev/null || die "python3 not found"

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/playbooks" "$STAGE/examples" "$STAGE/skills/instagram-reel-script"

san() { # san SRC DEST [extra sanitise.py args...]
  local src="$1" dst="$2"; shift 2
  [[ "$(basename "$src")" =~ $NEVER_RE ]] && die "refusing to copy excluded file $src"
  "$PY" "$SAN" "$src" "$dst" --drop-topics "$DROP" "$@"
}

GEN_NOTE='> Generated by `scripts/sync_from_box.sh` from the box copy. Paths and account IDs are replaced with placeholders (see `.env.example`). Do not edit here; edit the box source and re-sync.'

# ---------- playbooks/ ----------
need "$Q9_MOTION_DIR/SCRIPT_PLAYBOOK.md"
san "$Q9_MOTION_DIR/SCRIPT_PLAYBOOK.md"          "$STAGE/playbooks/SCRIPT_PLAYBOOK.md" --rewrite-links playbook --header "$GEN_NOTE This is the living source of truth for reel scripts."
san "$Q9_MOTION_DIR/APPROVED_IDEAS.md"           "$STAGE/playbooks/APPROVED_IDEAS.md" --header "$GEN_NOTE"
san "$Q9_MOTION_DIR/INSTAGRAM_SCRIPT_METHOD.md"  "$STAGE/playbooks/INSTAGRAM_SCRIPT_METHOD.md" --header "$GEN_NOTE"
san "$Q9_REELS_DIR/COMMON_REEL_BRIEF.md"         "$STAGE/playbooks/COMMON_REEL_BRIEF.md" --header "$GEN_NOTE On a new machine, \`\$NODE_BIN\` is wherever Node 22 lives (or drop the PATH line if \`npx\` is already on PATH)."
san "$Q9_ROOT/style-study.md"                    "$STAGE/playbooks/style-study.md" --header "$GEN_NOTE"
san "$Q9_ROOT/WAITLIST-PLAN.md"                  "$STAGE/playbooks/WAITLIST-PLAN.md" --header "$GEN_NOTE Historical plan (17 Oct 2026). Sections about retired or out-of-scope channels are removed. Stale points: the Buffer free-plan cap is 10 posts per channel (not 10 in total), X is no longer a Buffer channel, and reel CTAs now say \"Join the waitlist in bio\". Check docs/ for the current process."

# ---------- examples/ ----------
copied_hashes=""
example_index=""
for R in $APPROVED_REELS; do
  mkdir -p "$STAGE/examples/$R"
  for SRC_DIR in "$Q9_REELS_DIR/$R" "$Q9_REELS_DIR/${R}_L2"; do
    [ -d "$SRC_DIR" ] || { [ "$SRC_DIR" = "$Q9_REELS_DIR/$R" ] && die "approved reel folder missing: $SRC_DIR"; continue; }
    # top level only: never descend into project/, audio/, ref_L2/ (media, caches, node_modules)
    while IFS= read -r -d '' f; do
      base="$(basename "$f")"
      [[ "$base" =~ $EXAMPLE_EXT_RE ]] || continue
      [[ "$base" =~ $NEVER_RE ]] && continue
      case "$base" in *.log) continue ;; esac
      h="$(sha256sum "$f" | cut -c1-64)"
      case " $copied_hashes " in *" $h "*) continue ;; esac   # skip byte-identical duplicates (e.g. SCRIPT_v1.md == SCRIPT.md)
      copied_hashes="$copied_hashes $h"
      out="$base"
      if [ "$SRC_DIR" != "$Q9_REELS_DIR/$R" ]; then
        case "$base" in BRIEF.md|NOTES.md) out="L2_$base" ;; esac
      fi
      [ -e "$STAGE/examples/$R/$out" ] && out="L2_$out"
      if [[ "$base" == *.md ]]; then
        san "$f" "$STAGE/examples/$R/$out" --rewrite-links example --header "$GEN_NOTE"
      else
        san "$f" "$STAGE/examples/$R/$out"
      fi
    done < <(find "$SRC_DIR" -maxdepth 1 -type f -print0 | sort -z)
  done
  example_index="$example_index
## $R
$(cd "$STAGE/examples/$R" && ls -1 | sed 's/^/- [&](.\/'"$R"'\/&)/')
"
done
cat > "$STAGE/examples/README.md" <<EOF
# Examples: approved reels (text only)

Generated by \`scripts/sync_from_box.sh\`. These are the canonical reference reels Pallav called "perfect" on 22 Nov 2026 (004 runway, 005 toxic hike). New scripts should read like them.

- \`SCRIPT*.md\`: script drafts and the approved voiceover (004: \`SCRIPT_v2_voiceover.md\`; 005: \`SCRIPT_APPROVED.md\`). Earlier drafts are kept to show what was rejected and why.
- \`CAPTION*.txt\`: Instagram and LinkedIn caption. \`THREADS.txt\`: the Threads version (500 characters or fewer).
- \`L2_BRIEF.md\`: the beat-by-beat build brief given to the L2 builder. \`L2_NOTES.md\`: the builder's notes and the parent QA/delivery log, IDs scrubbed.
- No audio, video, images, fonts or Hyperframes project files are included.
$example_index
EOF

# ---------- skills/ ----------
SKILL_SRC="$Q9_SKILLS_DIR/instagram-reel-script/SKILL.md"
need "$SKILL_SRC"
PATCH="$DEST/skills/instagram-reel-script/PLAYBOOK_PATCH.md"
SKILL_NOTE='> Snapshot of the box skill, made by `scripts/sync_from_box.sh`. **`playbooks/SCRIPT_PLAYBOOK.md` is the living source of truth**: where this skill and the playbook disagree, follow the playbook. The Quit 9to5 rules from the playbook that the generic skill lacks are appended at the end ("Quit 9to5 patch").'
san "$SKILL_SRC" "$STAGE/skills/instagram-reel-script/SKILL.md" --header "$SKILL_NOTE"
if grep -q "Pallav's corrections (21 Nov 2026)" "$SKILL_SRC"; then
  echo "note: box skill already contains the 21 Nov corrections; patch not appended"
else
  [ -f "$PATCH" ] || die "missing curated patch $PATCH"
  { echo; echo "---"; echo; cat "$PATCH"; } >> "$STAGE/skills/instagram-reel-script/SKILL.md"
fi

# ---------- scan the staged output before touching DEST ----------
echo "== secret scan of staged generated files"
SCAN_STAGE="$(mktemp -d)"; trap 'rm -rf "$STAGE" "$SCAN_STAGE"' EXIT
cp -r "$STAGE/." "$SCAN_STAGE/"; mkdir -p "$SCAN_STAGE/scripts"
[ -f "$DEST/scripts/secret-scan-allowlist.txt" ] && cp "$DEST/scripts/secret-scan-allowlist.txt" "$SCAN_STAGE/scripts/"
"$PY" "$SCRIPT_DIR/lib/secret_scan.py" "$SCAN_STAGE" || die "staged output failed the secret scan; DEST was not modified"

# ---------- diff + apply ----------
echo "== changes in generated folders"
changes=0
report() { echo "  $1 $2"; changes=$((changes+1)); }
while IFS= read -r -d '' f; do
  rel="${f#$STAGE/}"
  if [ ! -e "$DEST/$rel" ]; then report "ADDED   " "$rel"
  elif ! cmp -s "$f" "$DEST/$rel"; then report "CHANGED " "$rel"; fi
done < <(find "$STAGE" -type f -print0 | sort -z)
for d in playbooks examples; do
  [ -d "$DEST/$d" ] || continue
  while IFS= read -r -d '' f; do
    rel="${f#$DEST/}"
    [ -e "$STAGE/$rel" ] || report "REMOVED " "$rel"
  done < <(find "$DEST/$d" -type f -print0 | sort -z)
done
[ "$changes" -eq 0 ] && echo "  no changes"

if [ "$DRY_RUN" -eq 0 ] && [ "$changes" -gt 0 ]; then
  rm -rf "$DEST/playbooks" "$DEST/examples"
  cp -r "$STAGE/playbooks" "$STAGE/examples" "$DEST/"
  mkdir -p "$DEST/skills/instagram-reel-script"
  cp "$STAGE/skills/instagram-reel-script/SKILL.md" "$DEST/skills/instagram-reel-script/SKILL.md"
fi
[ "$DRY_RUN" -eq 1 ] && echo "  (dry run: nothing written)"

# ---------- upstream drift for curated scripts ----------
echo "== upstream drift for ported scripts (scripts/UPSTREAM.tsv)"
UP="$DEST/scripts/UPSTREAM.tsv"
drift=0
if [ -f "$UP" ]; then
  tmp_up="$(mktemp)"
  while IFS=$'\t' read -r repo_path src_path old_sha; do
    case "$repo_path" in ''|'#'*) echo -e "$repo_path\t$src_path\t$old_sha" >> "$tmp_up"; continue ;; esac
    src_abs="$(eval echo "$src_path")"
    if [ ! -f "$src_abs" ]; then
      echo "  MISSING  $src_path (ported to $repo_path)"; drift=$((drift+1)); new_sha="$old_sha"
    else
      new_sha="$(sha256sum "$src_abs" | cut -c1-64)"
      if [ "$new_sha" != "$old_sha" ]; then echo "  UPSTREAM CHANGED  $src_path -> re-port into $repo_path by hand, then rerun with --update-upstream"; drift=$((drift+1)); fi
    fi
    if [ "$UPDATE_UPSTREAM" -eq 1 ]; then echo -e "$repo_path\t$src_path\t$new_sha" >> "$tmp_up"; else echo -e "$repo_path\t$src_path\t$old_sha" >> "$tmp_up"; fi
  done < "$UP"
  if [ "$UPDATE_UPSTREAM" -eq 1 ] && [ "$DRY_RUN" -eq 0 ]; then mv "$tmp_up" "$UP"; echo "  upstream hashes updated"; else rm -f "$tmp_up"; fi
  [ "$drift" -eq 0 ] && echo "  none"
else
  echo "  (no scripts/UPSTREAM.tsv)"
fi

# ---------- final scan of the whole repo ----------
echo "== secret scan of $DEST"
"$PY" "$SCRIPT_DIR/lib/secret_scan.py" "$DEST" || die "repo failed the secret scan"

echo "== summary: $changes generated file change(s), $drift upstream script change(s)"
if [ -d "$DEST/.git" ]; then
  echo "next: review 'git -C \"$DEST\" diff', update CHANGELOG.md, then commit and push"
else
  echo "next: review the changes above and update CHANGELOG.md (no git repo yet)"
fi
